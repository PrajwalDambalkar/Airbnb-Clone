echo "Command: ${CYAN}time curl http://${EC2_IP}:5001/health${NC}"
echo "Capture: Response time measurement"
echo ""
echo -e "${YELLOW}Screenshot 7.2: Load Test (if JMeter available)${NC}"
echo "Steps:"
echo "1. Run JMeter test plan"
echo "2. Capture: Results tree, response times graph"
echo ""
echo -e "${YELLOW}Screenshot 7.3: Service Health Checks${NC}"
echo "Commands:"
echo "${CYAN}curl http://${EC2_IP}:5001/health${NC}"
echo "${CYAN}curl http://${EC2_IP}:5003/health${NC}"
echo "${CYAN}curl http://${EC2_IP}:5004/health${NC}"
echo "Capture: All health check responses"
echo ""
read -p "Press Enter when Section 7 screenshots are complete..."

