echo ""
echo -e "${YELLOW}Screenshot 6.2: Disk Usage${NC}"
echo "Command: ${CYAN}df -h${NC}"
echo "Capture: Disk space usage"
echo ""
df -h
echo ""
echo -e "${YELLOW}Screenshot 6.3: Network Connections${NC}"
echo "Command: ${CYAN}netstat -tulpn | grep LISTEN${NC}"
echo "Capture: Services listening on ports"
echo ""
sudo netstat -tulpn 2>/dev/null | grep LISTEN || netstat -an | grep LISTEN
echo ""
echo -e "${YELLOW}Screenshot 6.4: Docker Compose Config${NC}"
echo "Command: ${CYAN}cat docker-compose.aws.yml${NC}"
echo "Capture: Configuration file (can do in VS Code)"
echo ""
read -p "Press Enter when Section 6 screenshots are complete..."

# Section 7: Testing & Performance
clear
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  SECTION 7: Testing & Performance${NC}"
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo ""
