clear
echo -e "${BLUE}╔════════════════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║              Screenshot Capture Complete! ✅                   ║${NC}"
echo -e "${BLUE}╚════════════════════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "${GREEN}Checklist Summary:${NC}"
echo ""
echo "AWS Console:"
echo "  ✓ EC2 Dashboard"
echo "  ✓ Instance Details"
echo "  ✓ Security Groups"
